"""Modal app for LTX-2.3 (Lightricks), image-to-video -- backs
`vitals/adapters/ltx.py`. A joint video+audio DiT; audio output is
generated and discarded here (this project scores pixels only).

**License: PROVISIONALLY RESTRICTED.** The model card names the "LTX-2
Community License Agreement" but does not state its terms (it points to
GitHub). Registered `restricted=True` with an explicit "not yet verified"
note until the full text has been read -- the conservative default
(opt-in only), never an assumption of permissiveness. Update the
registry note, not just this docstring, once read.

Facts confirmed against the diffusers LTX-2 docs page (2026-09):
- Pipeline `LTX2ImageToVideoPipeline`; checkpoint `Lightricks/LTX-2.3-
  Diffusers`; diffusers from git main.
- Native 24 fps (`frame_rate=24.0`); frame counts on the VAE's causal
  grid 8k+1 (docs default 121). Example: guidance 3.0, 30 steps,
  `output_type="np", return_dict=False` -> `(video, audio)`.
- Memory: `enable_model_cpu_offload()` + `vae.enable_tiling()` ("usually
  necessary to avoid OOM when VAE decoding"). VRAM not stated; the base
  LTX-2 line is ~19B params -> A100-80GB chosen for margin, a starting
  choice to revisit after a measured call.
- Spatial dims must be multiples of 32; this project's 4:3 renders map
  to 640x480.
- Not gated.

Usage:
    modal deploy remote/modal_app_ltx.py
    python3 remote/call_ltx.py download_checkpoints
    python3 remote/call_ltx.py image2video --input-path frame.png --prompt "..." --save-path out.mp4
"""
import modal

GPU_TYPE = "A100-80GB"
# `diffusers/LTX-2.3-Diffusers`, NOT the `Lightricks/LTX-2.3-Diffusers` the
# diffusers docs page lists -- FOUND DIRECTLY on the first download: the
# Lightricks-org id returns 401 on an anonymous HF API GET (it does not
# publicly exist), which huggingface_hub surfaces as the misleading
# "outgoing traffic has been disabled" error -- the identical bug class the
# Hunyuan integration hit. The `diffusers/` org id returns 200. (`Lightricks/
# LTX-2.5-Diffusers` also exists -- a later upgrade, not switched to here
# because only 2.3's pipeline/frame constraints were verified.)
MODEL_ID = "diffusers/LTX-2.3-Diffusers"

app = modal.App("vitals-ltx")

ltx_cache = modal.Volume.from_name("vitals-ltx-cache", create_if_missing=True)

image = (
    modal.Image.debian_slim(python_version="3.11")
    .apt_install("git")
    # `av` (PyAV): FOUND DIRECTLY on the first real call (2026-09-11) --
    # LTX2ImageToVideoPipeline re-compresses the conditioning image with
    # H.264 CRF by default (`apply_image_conditioning_crf`, mimicking the
    # video-frame statistics it was trained on) and raises ImportError
    # without PyAV. Installed rather than bypassed with `crf=0`, so the
    # model runs under its own default conditioning path.
    .pip_install("torch>=2.4", "transformers>=4.45", "accelerate", "sentencepiece", "ftfy", "pillow", "numpy", "av")
    .pip_install("git+https://github.com/huggingface/diffusers")
    .env({"HF_HOME": "/cache/hf"})
)


@app.function(image=image, gpu=GPU_TYPE, volumes={"/cache": ltx_cache}, timeout=3600)
def download_checkpoints():
    import torch
    from diffusers import LTX2ImageToVideoPipeline
    LTX2ImageToVideoPipeline.from_pretrained(MODEL_ID, torch_dtype=torch.bfloat16)
    ltx_cache.commit()
    return "CHECKPOINTS_DOWNLOADED"


@app.function(image=image, gpu=GPU_TYPE, volumes={"/cache": ltx_cache}, timeout=1500)
def image2video(image, prompt: str, seed: int = 0, num_frames: int = 49,
                height: int = 480, width: int = 640,
                guidance_scale: float = 3.0, num_inference_steps: int = 30):
    """Runs ONE LTX-2.3 image-to-video generation, returns (T,H,W,3) uint8.
    Audio is generated by the joint model and discarded."""
    import numpy as np
    import torch
    from diffusers import LTX2ImageToVideoPipeline
    from PIL import Image

    pipe = LTX2ImageToVideoPipeline.from_pretrained(MODEL_ID, torch_dtype=torch.bfloat16)
    pipe.enable_model_cpu_offload()
    pipe.vae.enable_tiling()

    pil_image = Image.fromarray(np.asarray(image))
    generator = torch.Generator(device="cuda").manual_seed(seed)
    video, _audio = pipe(
        image=pil_image, prompt=prompt, width=width, height=height, num_frames=num_frames,
        frame_rate=24.0, num_inference_steps=num_inference_steps, guidance_scale=guidance_scale,
        generator=generator, output_type="np", return_dict=False,
    )
    ltx_cache.commit()

    frames = np.asarray(video[0])
    if frames.dtype != np.uint8:
        frames = (frames * 255).clip(0, 255).astype(np.uint8)
    return frames
