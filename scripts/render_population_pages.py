def _video_uri(scenario, name):
    import base64
    p = ROOT / "results" / "videos" / f"{scenario}_{name}_grid.mp4"
    if not p.exists():
        return None
    return "data:video/mp4;base64," + base64.b64encode(p.read_bytes()).decode("ascii")


def _reel(all_stats, rsr):
    """The front-page reel (user, 2026-09-16: "bring some of the videos to
    the front as some visualization thing"): the headline scenario's
    generated clips, one per real model, plus the instrument ideal's clip
    of the same episodes for the eye to compare against. Each tile links
    to its population page. ~200 KB per clip, embedded like the pages'."""
    headline = rsr.HEADLINE_SCENARIO
    tiles = []
    for st in sorted(all_stats, key=lambda s: -s["rmvt"] if s["rmvt"] == s["rmvt"] else 0):
        if st["scenario"] != headline:
            continue
        uri = _video_uri(headline, st["model_backend"])
        if uri is None:
            continue
        vi = rsr.fmt(st["vi50"]) + ("" if st["vi50"] == float("inf") else " s")
        tiles.append(f'<a href="{headline}_{st["model_backend"]}.html"><video autoplay muted loop playsinline src="{uri}"></video>'
                     f'<div class="cap"><b>{html.escape(st["model_backend"])}</b><span>VI₅₀ {html.escape(vi)} · RMVT {rsr.fmt(st["rmvt"])} s</span></div></a>')
    ideal = _video_uri(headline, "truth_render")
    if ideal is not None:
        tiles.append(f'<a href="#"><video autoplay muted loop playsinline src="{ideal}"></video>'
                     f'<div class="cap"><b class="ideal">ideal (instrument)</b><span>the true continuation, rendered — same episodes</span></div></a>')
    if not tiles:
        return ""
    return (f'<h2 style="font-size:15px;margin:0 0 8px">{html.escape(headline)}</h2>'
            f'<p class="note">Three episodes side by side per model. Green border: the rendered prefix the model saw; red border: its continuation. '
            f'Green marker: the true object; red marker: what Phi reconstructed from the model\'s pixels.</p>'
            f'<div class="reel">{"".join(tiles)}</div>')


def render_pages(all_stats, omitted=()):
    PAGES_DIR.mkdir(parents=True, exist_ok=True)
    import render_score_report as rsr
    ordered = sorted(all_stats, key=lambda s: (rsr.scenario_sort_key(s["scenario"]), s["model_backend"]))
    groups = {}
    tmax_by_scenario = {}
    for st in ordered:
        name = f"{st['scenario']}_{st['model_backend']}.html"
        (PAGES_DIR / name).write_text(build_page(st, rsr))
        vi = rsr.fmt(st["vi50"])
        tmax = float(st["t_max"]); tmax_by_scenario[st["scenario"]] = tmax
        # RMVT as a bar against the episode horizon (a model that stays
        # valid the whole way fills the bar), then the number.
        w = max(0.0, min(1.0, st["rmvt"] / tmax)) * 100 if st["rmvt"] == st["rmvt"] else 0.0
        groups.setdefault(st["scenario"], []).append(
            f"<tr><td><a href='{name}'>{html.escape(st['model_backend'])}</a></td><td class='num'>{st['n']}</td>"
            f"<td class='num'>{vi}</td><td class='num'><span class='bar'><i style='--w:{w:.0f}%'></i></span>{rsr.fmt(st['rmvt'])}</td>"
            f"<td>{_chips(st['prof'], st['censoring'])}</td></tr>")
    # Rendered truth beside every scenario (user, 2026-09-16: "update the
    # webpage with the rendered truth"): the instrument ideal's clip -- the
    # true continuation rendered through the same codec and tracked by the
    # same Phi -- sits next to the table so the ceiling every row is judged
    # against is visible, not just a number.
    def _truth_tile(scenario):
        uri = _video_uri(scenario, "truth_render")
        if uri is None:
            return ""
        return (f'<figure class="truth"><video autoplay muted loop playsinline src="{uri}"></video>'
                f'<figcaption>rendered truth · the true continuation through the same renderer, codec and tracker</figcaption></figure>')
    sections = "".join(
        f"<div class='group'><h2>{html.escape(scenario)}</h2><div class='grow'>"
        f"<table><thead><tr><th>model</th><th>episodes</th><th>VI₅₀ (s)</th>"
        f"<th>RMVT (s) · of {tmax_by_scenario[scenario]:.0f} s</th><th>episodes terminated, by channel</th></tr></thead><tbody>{''.join(rows)}</tbody></table>"
        f"{_truth_tile(scenario)}</div></div>"
        for scenario, rows in groups.items())
    index = (f"<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width, initial-scale=1'>"
             f"<title>VITALS</title><style>{INDEX_CSS}</style></head><body><main class='index'>"
             f"<div class='hero'><h1>VITALS</h1><span class='tag'>physics consistency of video world models</span></div>"
             f"<p class='lead'>Each model continues a rendered physical scene; its pixels are measured back into object state and scored "
             f"against a calibrated reference ensemble. VI₅₀ is the time by which half the episodes have failed a physical check; "
             f"RMVT is the mean time an episode stays valid. Open a population to trace its curves.</p>"
             + _reel(all_stats, rsr) + sections + "</main></body></html>")
    (PAGES_DIR / "index.html").write_text(index)
    return PAGES_DIR / "index.html"


def main():
    import render_score_report as rsr
    from vitals.adapters import REAL_MODEL_BACKENDS, MODEL_REGISTRY
    from vitals.stats.survival import bootstrap_vi_delta
    from vitals.detect.events import Event
    all_results = rsr.discover_all()
    pages = sorted((s, b) for (s, b) in all_results if b in REAL_MODEL_BACKENDS)
    pages, omitted = rsr.apply_supersession(pages, all_results, MODEL_REGISTRY)
    stats = [rsr.compute_stats(s, b, all_results, bootstrap_vi_delta, Event) for s, b in pages]
    out = render_pages(stats, omitted)
    print(f"-> {out} ({len(stats)} page(s))")


if __name__ == "__main__":
    main()
