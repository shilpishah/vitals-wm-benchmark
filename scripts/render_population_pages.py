def _step_path(t, S, x0, y0, W, H, tmax, t_end=None):
    """SVG path for a right-continuous step function on [0, tmax]."""
    pts = []
    xs = lambda tt: x0 + W * max(0.0, min(tt, tmax)) / tmax
    ys = lambda ss: y0 + H * (1.0 - ss)
    cur_s = 1.0
    pts.append(f"M{xs(0):.1f},{ys(1.0):.1f}")
    for tt, ss in zip(t, S):
        if tt > tmax:
            break
        pts.append(f"L{xs(tt):.1f},{ys(cur_s):.1f}")
        pts.append(f"L{xs(tt):.1f},{ys(ss):.1f}")
        cur_s = ss
    pts.append(f"L{xs(t_end if t_end is not None else tmax):.1f},{ys(cur_s):.1f}")
    return " ".join(pts)


def _survival_svg(sid, series, tmax, events, height=300):
    """series: list of dict(name, color, t, S, t_end). events: list of
    dict(t, risk, n) for the model's own event rug."""
    Wv, Hv = 900, height
    x0, y0, W, H = 52, 18, Wv - 52 - 18, height - 18 - 44
    parts = [f'<svg id="{sid}" viewBox="0 0 {Wv} {Hv}" xmlns="http://www.w3.org/2000/svg" role="img">']
    parts.append(f'<g class="plot" data-w="{W}" data-h="{H}" data-x0="{x0}" data-y0="{y0}">')
    # grid + axes
    for k in range(0, 5):
        yy = y0 + H * (1 - k / 4)
        parts.append(f'<line x1="{x0}" y1="{yy:.1f}" x2="{x0 + W}" y2="{yy:.1f}" stroke="#eceef1" stroke-width="1"/>')
        parts.append(f'<text x="{x0 - 8}" y="{yy + 4:.1f}" font-size="11" fill="#6b6b76" text-anchor="end">{k / 4:.2f}</text>')
    n_ticks = int(tmax) + 1
    for k in range(0, 2 * n_ticks + 1):
        tt = k * 0.5
        if tt > tmax + 1e-9:
            break
        xx = x0 + W * tt / tmax
        parts.append(f'<line x1="{xx:.1f}" y1="{y0 + H}" x2="{xx:.1f}" y2="{y0 + H + 4}" stroke="#b7b7bf" stroke-width="1"/>')
        parts.append(f'<text x="{xx:.1f}" y="{y0 + H + 17}" font-size="11" fill="#6b6b76" text-anchor="middle">{tt:g}</text>')
    parts.append(f'<text x="{x0 + W / 2:.1f}" y="{Hv - 4}" font-size="11" fill="#6b6b76" text-anchor="middle">time (s)</text>')
    parts.append(f'<line x1="{x0}" y1="{y0}" x2="{x0}" y2="{y0 + H}" stroke="#dcdce2"/>')
    parts.append(f'<line x1="{x0}" y1="{y0 + H}" x2="{x0 + W}" y2="{y0 + H}" stroke="#dcdce2"/>')
    # event rug (model only)
    for e in events:
        xx = x0 + W * e["t"] / tmax
        parts.append(f'<line x1="{xx:.1f}" y1="{y0 + H - 7}" x2="{xx:.1f}" y2="{y0 + H}" stroke="#2563EB" stroke-opacity="0.55" stroke-width="1"/>')
    for s in series:
        d = _step_path(s["t"], s["S"], x0, y0, W, H, tmax, t_end=s.get("t_end"))
        parts.append(f'<path d="{d}" fill="none" stroke="{s["color"]}" stroke-width="2" stroke-linejoin="round"/>')
        if s.get("t_end") is not None and s["t_end"] < tmax:      # censored plateau past the last event
            xs = x0 + W * s["t_end"] / tmax; ys = y0 + H * (1 - s["S"][-1] if s["S"] else 0)
            parts.append(f'<line x1="{xs:.1f}" y1="{ys:.1f}" x2="{x0 + W}" y2="{ys:.1f}" stroke="{s["color"]}" stroke-width="2" stroke-dasharray="3 5" stroke-opacity="0.6"/>')
    parts.append(f'<line class="cross" x1="0" y1="{y0}" x2="0" y2="{y0 + H}" stroke="#17171b" stroke-width="1" stroke-opacity="0.6" visibility="hidden"/>')
    parts.append("</g></svg>")
    return "\n".join(parts)


def _lambda_svg(levels, height=200):
    """VI50 and RMVT vs lambda, log-x, no interaction needed."""
    import math
    Wv, Hv = 900, height
    x0, y0, W, H = 52, 18, Wv - 52 - 18, height - 18 - 44
    lams = [l["lam"] for l in levels]
    lx = lambda lam: x0 + W * (math.log2(lam) - math.log2(min(lams))) / max(1e-9, math.log2(max(lams)) - math.log2(min(lams)))
    ymax = max([l["rmvt"] for l in levels] + [l["vi50"] for l in levels if l["vi50"] != float("inf")] + [1.0]) * 1.1
    ly = lambda v: y0 + H * (1 - min(v, ymax) / ymax)
    parts = [f'<svg viewBox="0 0 {Wv} {Hv}" xmlns="http://www.w3.org/2000/svg" role="img">']
    for k in range(5):
        yy = y0 + H * (1 - k / 4)
        parts.append(f'<line x1="{x0}" y1="{yy:.1f}" x2="{x0 + W}" y2="{yy:.1f}" stroke="#eceef1"/>')
        parts.append(f'<text x="{x0 - 8}" y="{yy + 4:.1f}" font-size="11" fill="#6b6b76" text-anchor="end">{ymax * k / 4:.1f}</text>')
    for lam in lams:
        parts.append(f'<text x="{lx(lam):.1f}" y="{y0 + H + 17}" font-size="11" fill="#6b6b76" text-anchor="middle">λ={lam:g}</text>')
    parts.append(f'<text x="{x0 + W / 2:.1f}" y="{Hv - 4}" font-size="11" fill="#6b6b76" text-anchor="middle">reference-band scale λ (log)</text>')
    # Labels: RMVT above its point, VI50 below its point (2026-09-12, user:
    # "some of the numbers are being overlaid over each other") -- the two
    # curves meet wherever a model sits at the floor or both saturate, and
    # two labels above the same point printed on top of each other.
    for key, color, dy, baseline in (("rmvt", "#17171b", -7, "auto"), ("vi50", "#2563EB", 15, "hanging")):
        pts = [(lx(l["lam"]), ly(l[key] if l[key] != float("inf") else ymax)) for l in levels]
        d = " ".join(("M" if i == 0 else "L") + f"{x:.1f},{y:.1f}" for i, (x, y) in enumerate(pts))
        parts.append(f'<path d="{d}" fill="none" stroke="{color}" stroke-width="2"/>')
        for l, (x, y) in zip(levels, pts):
            lab = "∞" if l[key] == float("inf") else f"{l[key]:.2f}"
            parts.append(f'<text x="{x:.1f}" y="{y + dy:.1f}" font-size="10.5" fill="{color}" text-anchor="middle">{lab}</text>')
    parts.append("</svg>")
    return "\n".join(parts)


def build_page(st, rsr):
    scenario, model = st["scenario"], st["model_backend"]
    s = st["model_data"]["survival"]
    tmax = float(st["t_max"])
    series = []
    for name in rsr.series_order(st):
        d = rsr.series_data(st, name)
        km = d["survival"]["kaplan_meier"]
        series.append(dict(name=name, color=rsr.series_color(st, name), t=km["t"], S=km["S"],
                           t_end=(km["t"][-1] if km["t"] else 0.0)))
    # model's event rug, grouped by (time, risk)
    grouped = {}
    for e in s["events"]:
        if not e["censored"]:
            k = (round(e["time"], 3), e["risk"]); grouped[k] = grouped.get(k, 0) + 1
    events = [dict(t=t, risk=r, n=n) for (t, r), n in sorted(grouped.items())]
    lh_series, lh_events = [], []
    if st["lh"] is not None:
        for name, block in [(model, st["lh"])] + st["lh_baselines"]:
            km = block["kaplan_meier"]
            lh_series.append(dict(name=name, color=rsr.series_color(st, name), t=km["t"], S=km["S"], t_end=(km["t"][-1] if km["t"] else 0.0)))
        g2 = {}
        for e in st["lh"]["events"]:
            if not e["censored"]:
                k = round(e["time"], 3); g2[k] = g2.get(k, 0) + 1
        lh_events = [dict(t=t, risk="R4", n=n) for t, n in sorted(g2.items())]

    # Shares of EPISODES (not of terminations), same normalization as the
    # PDF's failure-mode chart (2026-09-12): a series that terminated one
    # episode must not read like one that terminated all of them.
    fired = 1.0 - st["censoring"]
    prof = ", ".join(f"{k} {v * fired * 100:.0f}%" for k, v in sorted(st["prof"].items()))
    # Shares of episodes terminated, by channel; nothing else on this card
    # (user, 2026-09-12: a "% valid" clause "makes it sound like none of the
    # results were valid"). Survival at horizons has its own card.
    prof = (prof + " of episodes terminated") if prof else "no terminations"
    S_at = " · ".join(f"S({h}) {v:.2f}" for h, v in st["S_at"].items())
    cards = [("VI₅₀", f"{rsr.fmt(st['vi50'])}{'' if st['vi50'] == float('inf') else ' s'}", f"CI [{rsr.fmt(st['ci'][0])}, {rsr.fmt(st['ci'][1])}]"),
             ("RMVT", f"{rsr.fmt(st['rmvt'])} s", "restricted mean validity time"),
             ("Episodes", f"{st['n']}", f"censoring {rsr.fmt(st['censoring'])}"),
             ("Failure modes", prof, "share of episodes, by channel"),
             ("Survival at horizons", S_at, "")]
    if st["lh"] is not None:
        cards.append(("R4 long-horizon", f"{(1 - st['lh']['censoring_rate']) * 100:.0f}% fired", f"VI₅₀ {rsr.fmt(st['lh']['vi50'])}"))
    strip = "".join(f'<div class="stat"><div class="k">{html.escape(k)}</div><div class="v">{html.escape(v)}</div><div class="s">{html.escape(sub)}</div></div>' for k, v, sub in cards)
    legend = "".join(f'<span style="color:{x["color"]}">{html.escape(x["name"])}</span>' for x in series)
    notes = []
    for b, d in st["baselines"]:
        if "recensored_from_t_max" in d:
            notes.append(f"{b} re-censored at {tmax:.2f}s (scored over {d['recensored_from_t_max']:.2f}s)")
    for b in st["missing_baselines"]:
        notes.append(f"{b}: not run for this scenario")
    from vitals.adapters import MODEL_REGISTRY as _REG
    if _REG.get(model, {}).get("seed_reproducible", True) is False:
        notes.append("seed_reproducible = False: the provider accepts no seed, so re-running does not reproduce these videos; "
                     "the comparison is paired on episodes (same prefix and initial condition per seed for every model), "
                     "not on the provider's sampler")
    if "R5" in st.get("channels", []):
        notes.append("theta_R5 is calibrated on this population's own render environment and is not portable across machines")

    import datetime
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    body = [f'<a class="back" href="index.html">← all populations</a>',
            f"<h1>{html.escape(model)} · {html.escape(scenario)}</h1>",
            f'<p class="sub">real model vs. ideals and trivial baselines, scored through the same calibrated thresholds · page generated {stamp}'
            + (" · " + "; ".join(notes) if notes else "") + "</p>",
            f'<div class="strip">{strip}</div>',
            "<section><h2>Validity over time</h2>",
            '<p class="note">Kaplan–Meier fraction of episodes still valid. Move along the chart: each series is read out at that instant, and the model\'s most recent drop is named with its diagnosed channel. Ticks along the axis mark every individual model episode\'s event time.</p>',
            '<div class="chart">', _survival_svg("km", series, tmax, events),
            '<div class="readout" id="km-ro"><span class="t">move along the curve</span></div></div>',
            f'<div class="legend">{legend}</div></section>']
    if lh_series:
        legend2 = "".join(f'<span style="color:{x["color"]}">{html.escape(x["name"])}</span>' for x in lh_series)
        body += ["<section><h2>R4 long-horizon consistency</h2>",
                 '<p class="note">Independent channel: cumulative drift below the first-crossing thresholds (CUSUM). Not part of the precedence race above.</p>',
                 '<div class="chart">', _survival_svg("lh", lh_series, tmax, lh_events, height=240),
                 '<div class="readout" id="lh-ro"><span class="t">move along the curve</span></div></div>',
                 f'<div class="legend">{legend2}</div></section>']
    if st.get("rescore"):
        body += ["<section><h2>Resolution: VI₅₀ and RMVT vs. reference-band scale</h2>",
                 '<p class="note">The same cached episodes re-scored against wider reference bands (λ). Where VI₅₀ leaves the floor is where the model becomes rankable; RMVT is defined at every λ.</p>',
                 '<div class="chart">', _lambda_svg(st["rescore"]["levels"]), "</div>",
                 '<div class="legend"><span style="color:#17171b">RMVT (s)</span><span style="color:#2563EB">VI₅₀ (s)</span></div></section>']
    # Generated video (2026-09-12, user: "add the results video/generated
    # video into it so that users can also see how their models are
    # performing beyond just the stats"): the population's own annotated
    # grid (3 episodes side by side) and, when it exists, the instrument
    # ideal's grid for the SAME seeds -- a perfect continuation of the same
    # episodes, for the eye to compare against. Relative paths: the pages
    # live in results/pages/, the videos in results/videos/.
    # Embedded as data URIs (2026-09-12, user: "the videos on it are not
    # working"): the files, paths and encoding were all valid (H.264 High,
    # yuv420p), so the failure was the viewer refusing local media through a
    # relative file:// path -- IDE previews do that. A self-contained page
    # has no path to refuse; ~200 KB per video. Muted autoplay is allowed
    # by every browser, so the clips start on load.
    import base64
    vids = []
    for name, label in ((model, f"{model} — generated continuation"),
                        ("truth_render", "ideal (instrument) — the true continuation, rendered, same seeds")):
        p = ROOT / "results" / "videos" / f"{scenario}_{name}_grid.mp4"
        if p.exists():
            uri = "data:video/mp4;base64," + base64.b64encode(p.read_bytes()).decode("ascii")
            vids.append(f'<figure style="margin:0"><video controls autoplay muted loop playsinline '
                        f'src="{uri}"></video><figcaption class="note">{html.escape(label)}</figcaption></figure>')
    if vids:
        body += ["<section><h2>Generated video</h2>",
                 '<p class="note">Three episodes side by side. Green border: the real rendered prefix the model was conditioned on; red border: the model\'s continuation. '
                 'Green marker: the true object position; red marker: the position Phi reconstructed from the model\'s pixels — the gap between them is what the channels score.</p>',
                 '<div style="display:grid; gap:14px">' + "".join(vids) + "</div></section>"]
    rows = "".join(f"<tr><td>{html.escape(l)}</td></tr>" for l in rsr.readout_lines(st))
    body += ["<section><h2>Computed readout</h2>", f"<table>{rows}</table></section>"]
    script = (f"<script>{JS}\nattach('km', {json.dumps(series)}, {tmax}, {json.dumps(events)});\n"
              + (f"attach('lh', {json.dumps(lh_series)}, {tmax}, {json.dumps(lh_events)});\n" if lh_series else "") + "</script>")
    return (f"<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width, initial-scale=1'>"
            f"<title>{html.escape(model)} · {html.escape(scenario)} — VITALS</title><style>{CSS}</style></head><body><main>"
            + "\n".join(body) + "</main>" + script + "</body></html>")


