"""Video visualizer (AGENT.md M6, 2026-08: "build the video visualizer").
Produces a REAL local mp4 -- no browser, no HTML -- showing a real
generated-video episode with two markers drawn directly on the actual
frames: TRUE physics position (green) vs. Phi's RECONSTRUCTED position
from the generated video (red). Makes the position-error finding from the
Cosmos population run (mean 0.92m, ~61% of true displacement) watchable
frame by frame instead of only a number.

Also draws a solid colored BORDER around every frame (2026-08, requested
directly: "is there any way to indicate when the reference video/episode
ends and real model starts, like a green border for the reference frames
and red border for what's generated by the real model") -- GREEN for
every frame in the real, ground-truth conditioning prefix, RED for every
frame the model itself generated. This is a visually unambiguous,
always-on cue for exactly the prefix/continuation boundary this script
already knows precisely (`args.prefix_frames`) -- distinct from the
green/red circle MARKERS above, which encode true-vs-reconstructed
POSITION, not which segment a frame belongs to. The two conventions look
similar (both green=real/true, red=generated/reconstructed) by design,
not by coincidence -- green is "ground truth" and red is "the model's
own output" throughout this whole visualizer, whether that's a position
or a frame.

Costs exactly ONE real GPU call (the Phi/SAM2 reconstruction) when a
cached prefix+continuation pair already exists locally (e.g. from an
earlier scripts/run_cosmos_output_through_phi.py or scripts/
run_cosmos_population.py run) -- does NOT call Cosmos again. Saves the
reconstructed positions to a local .npz alongside the video, so re-running
the ANNOTATION step alone (different marker style, etc.) never re-pays
for GPU time -- pass --positions-cache to reuse it.

--model (2026-08, real gap found directly: "why are the videos only
getting saved from occlusion_corridor... where are the ones from ramp/
ramp w friction" -- scripts/run_model_population.py, the script every
statistically-powered Cosmos/Wan population in this project actually
comes from, generates, scores, and DISCARDS every episode's frames in
memory by design, for every scenario, occlusion_corridor included --
nothing was ever saved anywhere. The one existing video (occlusion_
corridor, Wan, seed 1) came from a one-off manual `remote/call_wan.py`
invocation during early validation, not from any population run.) --
alternative to --continuation-path: calls the SAME `make_generate_fn`
dispatch scripts/run_model_population.py itself uses (one real,
freshly-paid-for model call, not reusing anything), saves the RAW output
to results/videos/<scenario>_<model>_seed<seed>_raw.mp4 for its own
record BEFORE annotating it, exactly the missing step.

    python3 scripts/render_annotated_comparison_video.py \\
        --scenario occlusion_corridor --seed 1 \\
        --continuation-path /tmp/cosmos_continuation.mp4 \\
        --save-path /tmp/cosmos_annotated.mp4

    python3 scripts/render_annotated_comparison_video.py \\
        --scenario ramp_descent_high_friction --model cosmos --seed 1 \\
        --save-path results/videos/ramp_descent_high_friction_cosmos_seed1_annotated.mp4
"""
import argparse
import pathlib
import sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import numpy as np

from vitals.render.annotate import annotate_episode_frames


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--scenario", default="occlusion_corridor")
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--prefix-frames", type=int, default=30)
    parser.add_argument("--n-continuation-frames", type=int, default=60)
    # --prefix-path REMOVED (2026-08, real pre-existing bug found directly:
    # required=True but never once read in this function's own body -- the
    # prefix is always re-rendered locally a few lines below
    # (`renderer.render(conditioning, ...)`), which is cheap/local and
    # needs no cached file at all. Only the continuation genuinely has to
    # be cached, since it's the one real, paid-for model call.
    parser.add_argument("--continuation-path", default=None,
                        help="cached REAL generated continuation mp4 -- mutually exclusive with --model")
    parser.add_argument("--model", default=None, choices=["cosmos", "wan"],
                        help="generate a FRESH continuation instead of reading --continuation-path -- "
                             "one real, freshly-paid-for model call; raw output is saved to "
                             "results/videos/<scenario>_<model>_seed<seed>_raw.mp4 automatically")
    parser.add_argument("--save-path", required=True)
    parser.add_argument("--positions-cache", default=None,
                        help="load/save reconstructed positions here (.npz) -- skips the GPU call if present")
    parser.add_argument("--border-thickness", type=int, default=8,
                        help="pixels; 0 disables the prefix/continuation border entirely")
    args = parser.parse_args()
    if (args.continuation_path is None) == (args.model is None):
        parser.error("pass exactly one of --continuation-path (reuse an existing video) or "
                      "--model (generate a fresh one)")

    import yaml
    from vitals.types import EpisodeSpec
    from vitals.physics import make_backend
    from vitals.render.mujoco_renderer import MujocoRenderer
    from vitals.phi import scene_geometry as sg
    from vitals.adapters.base import prefix_of
    from vitals.adapters.video_utils import _read_video, _write_video, resample_to_target as _resample_to_target

    ROOT = pathlib.Path(__file__).resolve().parents[1]
    manifest = yaml.safe_load((ROOT / f"configs/manifests/{args.scenario}.yaml").read_text())
    spec = EpisodeSpec(name=manifest["name"], scene=manifest["scene"], target_property=manifest["target_property"],
                        band=manifest["band"], lam=manifest["lam"], n_reference=manifest["n_reference"],
                        horizon_s=manifest["horizon_s"], fps=manifest["fps"], seed=manifest.get("seed", 0),
                        perturb_mode=manifest.get("perturb_mode", "full"))
    rollout = make_backend("mujoco", scene=spec.scene)
    full = rollout(spec, seed=args.seed)
    conditioning = prefix_of(full, args.prefix_frames)

    cfg = sg.get(args.scenario)
    renderer = MujocoRenderer(spec.scene, height=240, width=320)
    prefix_frames_obj, prefix_gt = renderer.render(conditioning, cameras=cfg["camera"])
    frame0_mask = (prefix_gt.segmentation[0] == 0)

    if args.model is not None:
        sys.path.insert(0, str(ROOT / "scripts"))
        from run_model_population import make_generate_fn
        print(f"calling real {args.model} generate_fn (one fresh, real, paid-for model call)...")
        generate_fn = make_generate_fn(args.model, args.scenario)
        # already resampled to this project's own fps/resolution by the
        # adapter's own generate_fn (same convention VideoWorldModel.
        # predict() relies on) -- no _read_video/_resample_to_target step
        # needed, unlike the --continuation-path branch below.
        continuation_frames = np.asarray(generate_fn(prefix_frames_obj.rgb, args.n_continuation_frames))
        raw_path = ROOT / "results" / "videos" / f"{args.scenario}_{args.model}_seed{args.seed}_raw.mp4"
        raw_path.parent.mkdir(parents=True, exist_ok=True)
        _write_video(continuation_frames, str(raw_path), fps=spec.fps)
        print(f"raw continuation saved -> {raw_path} (so this real call never has to be re-paid-for)")
    else:
        raw_continuation, raw_fps = _read_video(args.continuation_path)
        continuation_frames = _resample_to_target(
            raw_continuation, raw_fps, spec.fps, args.n_continuation_frames,
            (prefix_frames_obj.rgb.shape[1], prefix_frames_obj.rgb.shape[2]))

    all_frames = np.concatenate([prefix_frames_obj.rgb, continuation_frames], axis=0)
    n_total = all_frames.shape[0]

    cache_path = pathlib.Path(args.positions_cache) if args.positions_cache else None
    if cache_path and cache_path.exists():
        print(f"loading cached reconstructed positions from {cache_path} (no GPU call)")
        recon_pos = np.load(cache_path)["recon_pos"]
    else:
        print("calling real Phi (SAM2/DINOv2) reconstruction on Modal (one real GPU call)...")
        import modal
        phi_fn = modal.Function.from_name("vitals-phi", "run_phi_reconstruct_from_frames")
        full_traj = phi_fn.remote(all_frames=all_frames, prefix_len=args.prefix_frames,
                                  scenario_name=args.scenario, frame0_mask=frame0_mask,
                                  cam_pos=prefix_gt.cam_pos, cam_mat=prefix_gt.cam_mat,
                                  fovy_deg=prefix_gt.fovy_deg, fps=spec.fps)
        recon_pos = full_traj.pos[:, 0]   # (T, 3) -- single tracked object
        if cache_path:
            np.savez(cache_path, recon_pos=recon_pos)
            print(f"cached reconstructed positions -> {cache_path} (re-runs won't re-pay for GPU)")

    true_pos = full.pos[:n_total, 0]

    print(f"annotating {n_total} frames (green=true physics, red=Phi-reconstructed-from-video, "
          f"border: green=real prefix, red=model-generated)...")
    annotated = annotate_episode_frames(all_frames, true_pos, recon_pos, prefix_gt.cam_pos, prefix_gt.cam_mat,
                                         prefix_gt.fovy_deg, args.prefix_frames,
                                         border_thickness=args.border_thickness)

    _write_video(annotated, args.save_path, fps=spec.fps)
    print(f"\n-> {args.save_path}  ({n_total} frames at {spec.fps}fps, {n_total/spec.fps:.2f}s)")
    print("green circle = true physics position, red circle = Phi-reconstructed position from the generated video")
    print(f"border: green = real conditioning prefix (frames 0-{args.prefix_frames - 1}, "
          f"{args.prefix_frames/spec.fps:.2f}s), red = model-generated continuation (frame {args.prefix_frames} onward)")


if __name__ == "__main__":
    main()
